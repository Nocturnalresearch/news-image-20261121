#!/usr/bin/env python3
"""make.fun news-image-20261121 entrypoint.

Copies the pre-drawn front page (entry.png, in this repository) to the
output directory as /output/entry.png. Standard library only, no network,
deterministic: the same bytes every run.
"""
import os
import shutil
import sys


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    src = os.path.join(here, "entry.png")
    out_dir = os.environ.get("MAKEFUN_OUTPUT_DIR", "/output")
    os.makedirs(out_dir, exist_ok=True)
    dst = os.path.join(out_dir, "entry.png")
    shutil.copyfile(src, dst)
    print("wrote", dst)
    return 0


if __name__ == "__main__":
    sys.exit(main())
